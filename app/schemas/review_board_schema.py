"""
Review Board Schemas - Data contracts for Multiple AI Review Board.
Defines models for idea inputs, evidence items, specialist agents,
individual feedback, challenge rounds, coordinator synthesis, and sessions.
"""

from typing import List, Optional, Dict, Any, Literal
from pydantic import BaseModel, Field, model_validator


class EvidenceItem(BaseModel):
    """Supporting evidence item provided with a startup idea."""
    id: str = Field(..., description="Unique evidence identifier, e.g., 'E1', 'E2'")
    source: str = Field(..., description="Source name, URL, or data origin")
    summary: str = Field(..., description="Summary of the empirical finding or claim")
    data_type: Literal["metric", "customer_interview", "market_report", "benchmark", "pilot", "anecdote", "other"] = Field(
        default="metric",
        description="Type of evidence"
    )


class StartupIdeaInput(BaseModel):
    """Full startup idea input capturing idea, customer, problem, solution, and evidence."""
    title: str = Field(..., min_length=2, max_length=150, description="Short name of the startup idea")
    idea: str = Field(..., min_length=10, description="Comprehensive description of the startup idea")
    target_customer: str = Field(..., min_length=3, description="Target market segment or user persona")
    problem: str = Field(..., min_length=5, description="Specific problem being solved")
    proposed_solution: str = Field(..., min_length=5, description="How the product solves the problem")
    evidence: List[EvidenceItem] = Field(
        default_factory=list,
        description="List of supporting evidence items with IDs (e.g. E1, E2)"
    )


class SpecialistAgentConfig(BaseModel):
    """Configuration for a single specialist agent on the review board."""
    id: str = Field(..., description="Unique agent identifier, e.g., 'spec_1'")
    role: str = Field(..., description="Domain specialist title (e.g., 'Infrastructure & eBPF Systems Architect')")
    expertise: str = Field(..., description="Specialist domain expertise and focus areas")
    mandate: str = Field(..., description="Specific review mandate and key questions to evaluate")
    rationale: str = Field(..., description="Why this specific perspective is essential for this idea")
    provider: Literal["mock", "openai", "gemini"] = Field(
        default="mock",
        description="AI provider to execute this specialist review"
    )
    model: str = Field(
        default="mock-deterministic",
        description="Model name (e.g., 'mock-deterministic', 'gpt-4o-mini', 'gemini-1.5-flash')"
    )
    simulate_failure: Optional[Literal["timeout", "provider_error", "malformed_output"]] = Field(
        default=None,
        description="Optional failure injection for demonstration/testing purposes"
    )


class ValidationExperiment(BaseModel):
    """Concrete experiment proposed to validate a critical assumption."""
    hypothesis: str = Field(..., description="The core assumption being tested")
    test_design: str = Field(..., description="Step-by-step experiment or pilot setup")
    success_metric: str = Field(..., description="Quantitative or qualitative threshold for success")


class SpecialistFeedback(BaseModel):
    """Independent feedback generated by a specialist agent."""
    specialist_id: str
    role: str
    provider: str
    model: str
    is_simulated: bool = True
    status: Literal["success", "failed", "timed_out"] = "success"
    error_message: Optional[str] = None
    
    strengths: List[str] = Field(default_factory=list, description="Key strengths from this specialist's angle")
    risks: List[str] = Field(default_factory=list, description="Critical risks or failure points")
    missing_assumptions: List[str] = Field(default_factory=list, description="Unstated or unverified assumptions")
    questions: List[str] = Field(default_factory=list, description="Probing questions for the founding team")
    validation_experiment: Optional[ValidationExperiment] = Field(
        default=None,
        description="Concrete validation experiment proposed by this specialist"
    )
    
    evidence_citations: List[str] = Field(
        default_factory=list,
        description="Valid evidence IDs cited in the review (e.g., ['E1'])"
    )
    invalid_citations: List[str] = Field(
        default_factory=list,
        description="Fabricated or unsupplied evidence IDs cited (flagged for reliability)"
    )
    assumptions_and_unknowns: List[str] = Field(
        default_factory=list,
        description="Explicitly labeled assumptions, uncertainties, or unbacked claims"
    )
    
    latency_ms: float = Field(default=0.0, description="Latency of the response in milliseconds")
    token_usage: Dict[str, int] = Field(
        default_factory=lambda: {"input_tokens": 0, "output_tokens": 0, "total_tokens": 0}
    )
    cost_estimate_usd: float = Field(default=0.0, description="Estimated cost in USD")


class ChallengeResponseItem(BaseModel):
    """A bounded challenge and response between two specialists."""
    challenger_id: str
    challenger_role: str
    target_specialist_id: str
    target_role: str
    challenge_point: str = Field(..., description="The contested assumption, tension, or reasoning challenged")
    response: str = Field(..., description="The target specialist's counter-argument or defense")
    reasoning_adjustment: str = Field(..., description="How reasoning or risk appraisal shifted after the challenge")
    is_simulated: bool = True


class EvidenceSufficiencyAssessment(BaseModel):
    """Coordinator's objective assessment of the evidence provided."""
    status: Literal["sufficient", "thin", "insufficient"] = Field(
        ...,
        description="Overall evidence rating"
    )
    analysis: str = Field(
        ...,
        description="Detailed explanation of what empirical backing exists vs what is unverified"
    )


class CoordinatorCombinedReview(BaseModel):
    """Synthesized combined review produced by the independent coordinator agent."""
    summary: str = Field(..., description="High-level synthesis of the review board's findings")
    priorities: List[str] = Field(
        default_factory=list,
        description="Prioritized list of immediate operational or strategic imperatives"
    )
    disagreements: List[str] = Field(
        default_factory=list,
        description="Key tensions and conflicting perspectives between specialists"
    )
    next_experiments: List[ValidationExperiment] = Field(
        default_factory=list,
        description="Consolidated, ranked validation experiments with highest information value"
    )
    evidence_sufficiency: EvidenceSufficiencyAssessment = Field(
        ...,
        description="Assessment of supplied evidence sufficiency"
    )
    failure_impact_analysis: Optional[str] = Field(
        default=None,
        description="Explicit explanation of how specialist failure(s) impacted confidence and conclusions"
    )
    disclaimer: str = Field(
        default="Decision support only. Not an investment recommendation. Consensus among AI agents does not constitute proof of market demand.",
        description="Mandatory advisory disclaimer"
    )
    latency_ms: float = 0.0
    token_usage: Dict[str, int] = Field(
        default_factory=lambda: {"input_tokens": 0, "output_tokens": 0, "total_tokens": 0}
    )
    cost_estimate_usd: float = 0.0


class BudgetConfig(BaseModel):
    """Reliability and budget controls for running a review board."""
    call_cap: int = Field(default=20, ge=1, le=50, description="Maximum total LLM calls allowed in session")
    token_cap: int = Field(default=50000, ge=1000, le=200000, description="Maximum total token budget")
    timeout_seconds: float = Field(default=12.0, ge=0.1, le=60.0, description="Per-call timeout limit in seconds")
    max_retries: int = Field(default=1, ge=0, le=1, description="Maximum retries on transient errors (at most 1)")


class ReviewBoardSession(BaseModel):
    """Full session state for saving, reopening, or rerunning a review board."""
    session_id: str
    created_at: str
    idea: StartupIdeaInput
    panel: List[SpecialistAgentConfig]
    budget_config: BudgetConfig
    
    specialist_reviews: List[SpecialistFeedback] = Field(default_factory=list)
    challenge_round: List[ChallengeResponseItem] = Field(default_factory=list)
    combined_review: Optional[CoordinatorCombinedReview] = None
    
    status: Literal["draft", "panel_generated", "in_progress", "completed", "partial_failure", "budget_stopped"] = "draft"
    
    execution_summary: Dict[str, Any] = Field(
        default_factory=lambda: {
            "total_latency_ms": 0.0,
            "total_tokens": 0,
            "total_cost_usd": 0.0,
            "calls_made": 0,
            "budget_stopped": False,
            "failures_encountered": 0
        }
    )


class GeneratePanelRequest(BaseModel):
    """Request to generate 3-5 specialists for an idea."""
    idea: StartupIdeaInput


class RunReviewRequest(BaseModel):
    """Request to execute a review board."""
    session_id: Optional[str] = None
    idea: StartupIdeaInput
    panel: List[SpecialistAgentConfig]
    budget_config: Optional[BudgetConfig] = None
